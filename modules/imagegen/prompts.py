"""生图｜提示词

做什么：三个提示词——
  1. PLAN_PROMPT     把用户需求拆成结构化规格，并判断信息够不够
  2. PROMPT_PROMPT   把规格写成一段给生图模型看的提示词
  3. RANDOM_PROMPT   需求不足又已经问过时，生成一个随机主题

被谁用：modules/imagegen/node.py。
"""

# ============ 1. 拆规格 ============

PLAN_PROMPT = """# 角色
你是一个图像设计助手。用户想要一张图，你要判断他的需求是否足够具体，并拆成结构化字段。

# 当前时间
{today}

# 用户之前说过的话
{history}

# 用户这次说
{query}

# 你要输出什么
只输出 JSON，不要解释、不要代码块标记：

{
  "enough": true 或 false,
  "spec": {
    "subject": "画面主体，例如：一只橘猫",
    "action": "主体在做什么，例如：坐在窗台上",
    "scene": "场景，例如：室内、雨夜街头",
    "style": "风格，例如：水彩、赛博朋克、写实摄影、像素风",
    "lighting": "光线，例如：清晨柔光、霓虹灯",
    "aspect": "比例，只能从 1:1 / 4:3 / 3:4 / 16:9 / 9:16 / 3:2 / 2:3 里选一个",
    "text_in_image": "图里要写的文字，没有就填空字符串",
    "negative": "不想要的东西，没有就填空字符串"
  },
  "missing": ["还缺哪些信息，用中文短语，例如：主体是什么"]
}

# 判断标准

enough = false 的情况（需求太空，画出来大概率不是用户想要的）：
  - 只说了「帮我画个图」「画一张」这类，完全没说什么内容
  - 说了要画图但主体完全不明确

enough = true 的情况：
  - 主体明确，哪怕其他字段空着（风格、光线你可以自己补）
  - 例如「画一只猫」「画个赛博朋克的城市」都算够

# 填字段的原则
- 用户说了什么就写什么，**不要自己编造具体细节**（用户没说猫的颜色，就不要写"橘色"）
- 风格、光线可以给**合理默认值**：用户没提风格就按题材选一个合适的（风景→写实摄影，卡通→插画）
- aspect 用户没说就用 1:1
- missing 只在 enough=false 时有意义，列出要问用户的
"""


