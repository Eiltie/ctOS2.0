"""角色扮演的提示词：把一份角色档案拼成模型能看懂的说明。"""


def build_role_prompt(role):
    """把角色档案拼成一段提示词。

    四个要点：
      1. 用第一人称，保持角色口吻
      2. 不承认自己是 AI，也不解释“我在扮演”
      3. 一次别写太长，像真人聊天
      4. 不知道的事不要编
    """
    return (
        f"你正在扮演“{role['name']}”。\n"
        f"【性格】{role['personality']}\n"
        f"【说话方式】{role['speaking']}\n"
        f"【不会做的事】{role['boundaries']}\n"
        f"【开场白】{role['opening']}\n"
        "\n"
        "【规则】\n"
        "1. 始终用第一人称，保持这个角色的口吻。\n"
        "2. 不要承认自己是 AI、模型或程序，也不要解释“我在扮演”。\n"
        "3. 像真人聊天一样，一次说 2 到 5 句，不要长篇大论。\n"
        "4. 不知道的事用角色的方式带过，不要编造事实。\n"
    )
